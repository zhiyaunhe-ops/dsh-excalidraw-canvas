import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const source = await readFile(new URL('dsh-embed/plugin/dsh-canvas-session/client.js', root), 'utf8');
await mkdir(new URL('plugin/', root), { recursive: true });
await writeFile(new URL('plugin/client.js', root), '// Generated by scripts/build-plugin-client.mjs from the shared browser implementation.\n' + source.replace('id: "dsh-canvas-session"', `id: "${manifest.name}"`));
